package com.aniko.data.librarypreferences

/**
 * Вид отображения экрана «Мои списки»: два режима, между которыми переключает кнопка в тулбаре.
 *
 * - [List] — «Список»: строки/карточки с прогрессом просмотра (название, «N из M», статус).
 * - [Grid] — «Сетка постеров»: плитки-постеры с бейджами рейтинга/избранного/статуса.
 *
 * Сам перечень не знает про размер окна: какой режим показывать, пока пользователь ничего не
 * выбирал, решает экран (см. `LibraryPreferencesStore.viewMode` — `null` значит «выбора не было»).
 */
enum class LibraryViewMode {
    List,
    Grid,
    ;

    /** Противоположный режим: кнопка-переключатель меняет ровно эти два вида местами. */
    fun toggled(): LibraryViewMode =
        when (this) {
            List -> Grid
            Grid -> List
        }
}
