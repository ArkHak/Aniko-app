package com.aniko.data.sync

/**
 * Текущее состояние сетевого подключения с точки зрения приложения (P10.T2).
 *
 * Три значения, а не `Boolean`, осознанно: [Unknown] — это НЕ «оффлайн». На старте процесса
 * платформенный монитор ещё не успел отдать первое значение (`NWPathMonitor` на iOS отвечает
 * асинхронно, `ConnectivityManager.NetworkCallback` — тоже), и показывать в этот момент баннер
 * «нет подключения» было бы ложной тревогой. UI (P10.T3) считает офлайном только [Offline], а
 * [SyncCoordinator] триггерит дренаж очереди на любом переходе «не-[Online] → [Online]», включая
 * самый первый [Unknown] → [Online] — он же заменяет собой разовый стартовый `drain()`.
 */
enum class ConnectivityStatus {
    /** Первое значение ещё не получено от платформы. */
    Unknown,

    /** Есть сетевой интерфейс, через который система готова маршрутизировать трафик. */
    Online,

    /** Подключения нет. */
    Offline,
    ;

    /**
     * Только [Offline] — см. KDoc типа про то, почему [Unknown] не считается офлайном.
     */
    val isOffline: Boolean get() = this == Offline
}
