package com.aniko.player

/*
 * Единственное место, где живёт ответ на вопрос «серия подходит к концу?».
 *
 * Им пользуются ДВЕ независимые фичи Фазы 8, и дублировать порог между ними нельзя (иначе они
 * рано или поздно разъедутся и авто-отметка «просмотрено» перестанет совпадать с моментом
 * появления баннера):
 * - P8.T4 — баннер «следующая серия через Nс»;
 * - P8.T8 — авто-отметка серии просмотренной.
 *
 * Логика лежит в `:shared:player`, а не в `composeApp`, по двум причинам: она оперирует
 * исключительно [EmbedVideoState] (то есть это часть контракта моста, а не UI), и только здесь
 * есть `commonTest` — в `composeApp` тестового source set'а нет вообще.
 */

/**
 * Порог «серия подходит к концу» — последние 20 секунд.
 *
 * Почему именно 20 с:
 * - это заметно больше, чем шаг обновления состояния моста (`setInterval(..., 500)` +
 *   `timeupdate` ~4 раза в секунду, см. [embedBridgeScript]), помноженный на максимальную
 *   скорость воспроизведения 2.0× (P8.T5): за один тик при 2× видео уходит на ~1 с, и окно
 *   в 20 с гарантированно не проскакивается целиком между двумя сообщениями;
 * - этого хватает на видимый обратный отсчёт баннера P8.T4 (пользователь успевает прочитать
 *   надпись и нажать «Отмена»), но недостаточно, чтобы перебить финальную сцену: типичный
 *   ED аниме-серии длится ~90 с, то есть баннер появляется уже глубоко в титрах;
 * - на этом же пороге серия считается досмотренной (P8.T8) — оставшиеся 20 с из ~24 минут
 *   это 1.4% хронометража, спорить о «досмотрел или нет» тут не о чем.
 */
const val END_OF_EPISODE_THRESHOLD_MS: Long = 20_000L

/**
 * Минимальная длительность, при которой [isNearEnd] вообще имеет смысл.
 *
 * Защита от короткого ролика в том же `<video>`: у большинства хостов до самой серии крутится
 * пре-ролл/заставка на 10–30 с, и без этой границы `duration <= порога` давало бы «серия
 * подходит к концу» уже на нулевой секунде рекламы — с мгновенным перескоком на следующую
 * серию и ложной отметкой «просмотрено». Минута выбрана как заведомо больший любого пре-ролла
 * и заведомо меньший самой короткой реальной серии (короткометражки ~3–4 мин).
 */
const val MIN_TRACKED_DURATION_MS: Long = 60_000L

/**
 * Допуск на «видео доиграло до конца».
 *
 * `currentTime` не обязан дотянуться ровно до `duration`: браузер останавливает счётчик на
 * последнем декодированном кадре, а состояние к нам приезжает тиками по 500 мс. Секунда —
 * с запасом больше тика и достаточно мало, чтобы не срабатывать раньше времени.
 */
private const val EPISODE_FINISH_EPSILON_MS: Long = 1_000L

/**
 * Сколько осталось до конца серии, или `null` — если этого нельзя знать.
 *
 * `null` возвращается, пока не найден `<video>` ([EmbedVideoState.isVideoFound]), пока не пришло
 * `loadedmetadata` ([EmbedVideoState.durationMs] == `null`, см. её KDoc) или если длительность
 * слишком мала для отслеживания (см. [MIN_TRACKED_DURATION_MS]). Именно `null`, а не `0`:
 * «до конца ноль» и «неизвестно» — разные вещи, и UI обязан их различать.
 */
fun EmbedVideoState.remainingMs(): Long? {
    val duration = durationMs?.takeIf { isVideoFound && it >= MIN_TRACKED_DURATION_MS } ?: return null
    return (duration - currentTimeMs).coerceAtLeast(0L)
}

/**
 * Серия подходит к концу — общий триггер P8.T4 (показать баннер) и P8.T8 (отметить просмотренной).
 *
 * @param thresholdMs окно «конца серии», по умолчанию [END_OF_EPISODE_THRESHOLD_MS]; параметр
 * существует ради тестов, продакшен-код передаёт дефолт.
 */
fun EmbedVideoState.isNearEnd(thresholdMs: Long = END_OF_EPISODE_THRESHOLD_MS): Boolean {
    val remaining = remainingMs() ?: return false
    return remaining <= thresholdMs
}

/**
 * Серия доиграна — момент фактического перехода на следующую (P8.T4).
 *
 * Отдельно от [isNearEnd]: баннер живёт всё окно порога, а переключать серию можно только когда
 * смотреть уже нечего.
 */
fun EmbedVideoState.isEpisodeFinished(): Boolean {
    val remaining = remainingMs() ?: return false
    return remaining <= EPISODE_FINISH_EPSILON_MS
}

/**
 * Обратный отсчёт баннера P8.T4 в секундах.
 *
 * Считается из [remainingMs], а не собственным таймером (требование плана: «триггер брать из
 * `EmbedVideoController.state`»), — иначе отсчёт разъедется с видео на первой же паузе, перемотке
 * или смене скорости. Округление вверх, чтобы не показать «0 с» за секунду до перехода.
 */
fun EmbedVideoState.secondsToEpisodeEnd(): Int? {
    val remaining = remainingMs() ?: return null
    return ((remaining + MILLIS_IN_SECOND - 1) / MILLIS_IN_SECOND).toInt()
}

private const val MILLIS_IN_SECOND = 1_000L
