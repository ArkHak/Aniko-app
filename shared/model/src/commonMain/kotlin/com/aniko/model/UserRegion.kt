package com.aniko.model

/**
 * Сетевой регион пользователя — по egress-IP (geo-IP), а НЕ по системной локали устройства:
 * запрос уходит через активный сетевой интерфейс пользователя, поэтому VPN естественно меняет
 * результат (VPN Нидерландов → `OTHER`, а не `RUSSIA`).
 *
 * Семантика fail-open (решение пользователя 2026-09-26): блокировка лицензированных
 * правообладателем тайтлов применяется ТОЛЬКО при [RUSSIA]. [UNKNOWN] (регион ещё не проверяли
 * или оба geo-запроса упали — например, нет сети) НЕ блокирует воспроизведение: закрывать доступ
 * «на всякий случай» нельзя, т.к. это наказало бы обычных пользователей за сбой сети/сервиса.
 */
enum class UserRegion {
    /** Регион неизвестен: не проверяли либо проверка завершилась сбоем — доступ открыт. */
    UNKNOWN,

    /** Egress-IP подтверждённо из РФ — применяется блокировка лицензированных тайтлов. */
    RUSSIA,

    /** Egress-IP подтверждённо НЕ из РФ — лицензионные ограничения РФ не действуют. */
    OTHER,
}
